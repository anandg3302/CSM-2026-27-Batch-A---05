def build_ai_detector_interpretation(
    status: AllowedAiDetectorStatus,
    selected_class: Optional[str] = None,
    selected_class_id: Optional[int] = None,
    artificial_score: Optional[float] = None,
    human_score: Optional[float] = None,
    decision_rule: AllowedAiDecisionRule = "model_class_selection",
    threshold: Optional[float] = None,
    limitations: Optional[List[str]] = None,
    transformation_context: Optional[AiTransformationContext] = None,
) -> AiDetectorInterpretation:
    """Build the standardized Step 14.1.6 AiDetectorInterpretation object."""
    tx_ctx = transformation_context or AiTransformationContext()
    lims = list(limitations) if limitations else list(DEFAULT_AI_DETECTOR_LIMITATIONS)

    if status != "available" or selected_class is None:
        return AiDetectorInterpretation(
            status="not_available",
            model_output=AiDetectorModelOutputSummary(
                selected_class=None,
                selected_class_id=None,
                artificial_score=None,
                human_score=None,
                score_type="uncalibrated_model_score",
                decision_rule=decision_rule,
                threshold=threshold,
            ),
            forensic_meaning=FORENSIC_MEANING_UNAVAILABLE,
            limitations=lims,
            interpretation_flags=[
                "model_unavailable",
                "not_provenance_evidence",
                "not_authenticity_proof",
            ],
            recommended_use=RECOMMENDED_AI_DETECTOR_USE,
            prohibited_inference=list(PROHIBITED_AI_DETECTOR_INFERENCES),
            transformation_context=tx_ctx,
        )

    norm_class = selected_class.strip().lower()
    if norm_class == "artificial":
        class_id = 0 if selected_class_id is None else selected_class_id
        meaning = FORENSIC_MEANING_ARTIFICIAL
        class_flag = "model_class_artificial"
    else:
        norm_class = "human"
        class_id = 1 if selected_class_id is None else selected_class_id
        meaning = FORENSIC_MEANING_HUMAN
        class_flag = "model_class_human"

    flags = [
        "model_available",
        "uncalibrated_score",
        "no_threshold",
        "domain_shift_risk",
        "transformation_sensitivity",
        "not_provenance_evidence",
        "not_authenticity_proof",
        "single_model_signal",
        class_flag,
    ]
    if tx_ctx.documented:
        flags.append("documented_transformation_context")

    return AiDetectorInterpretation(
        status="available",
        model_output=AiDetectorModelOutputSummary(
            selected_class=norm_class,
            selected_class_id=class_id,
            artificial_score=artificial_score,
            human_score=human_score,
            score_type="uncalibrated_model_score",
            decision_rule=decision_rule,
            threshold=threshold,
        ),
        forensic_meaning=meaning,
        limitations=lims,
        interpretation_flags=flags,
        recommended_use=RECOMMENDED_AI_DETECTOR_USE,
        prohibited_inference=list(PROHIBITED_AI_DETECTOR_INFERENCES),
        transformation_context=tx_ctx,
    )


