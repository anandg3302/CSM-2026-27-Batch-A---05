class AiDetectorPreprocessingInfo(BaseModel):
    """Exact preprocessing pipeline matching the official upstream preprocessor_config.json."""

    image_mode: str = Field(default="RGB", description="Decoded in-memory image channel order")
    resize_dimensions: str = Field(default="224x224", description="Target resize resolution from preprocessor_config.json")
    resample_filter: str = Field(
        default="Image.Resampling.BICUBIC (resample=3)",
        description="Resampling filter specified by resample=3 in preprocessor_config.json",
    )
    crop_behavior: str = Field(
        default="none (direct resize to 224x224)",
        description="Crop behavior (do_resize=true, no center crop)",
    )
    value_scaling: str = Field(
        default="[0, 255] uint8 -> [0.0, 1.0] float32",
        description="Pixel intensity scaling before normalization",
    )
    tensor_layout: str = Field(
        default="NCHW (1, 3, 224, 224) float32",
        description="Input tensor shape and data type",
    )
    normalization_mean: List[float] = Field(
        default_factory=lambda: list(OFFICIAL_IMAGE_MEAN),
        description="Per-channel normalization mean [0.485, 0.456, 0.406]",
    )
    normalization_std: List[float] = Field(
        default_factory=lambda: list(OFFICIAL_IMAGE_STD),
        description="Per-channel normalization standard deviation [0.229, 0.224, 0.225]",
    )
    class_ordering: Dict[str, str] = Field(
        default_factory=lambda: {"0": "artificial", "1": "human"},
        description="Class index mapping from config.json id2label",
    )
    logits_handling: str = Field(
        default="2-class softmax over raw logits with argmax model_class_selection",
        description="How raw output logits are converted into an uncalibrated model score and class decision",
    )


